from __future__ import annotations

import pandas as pd
import streamlit as st

from insights import CRITICAL, WARNING, WATCH, generate_recommendations
from ui.theme import BAD, GOOD, MUTE, PRIMARY, WARN, action_card, kpi, page_head, section

_SEVERITY_STYLE = {
    CRITICAL: (BAD, "CRITICAL"),
    WARNING: (WARN, "WARNING"),
    WATCH: (PRIMARY, "WATCH"),
}


def page_summary(d: dict[str, pd.DataFrame]) -> None:
    page_head("Executive Summary",
              "Rule-based highlights across occupancy, financials, maintenance, and "
              "leasing — ranked by what needs attention first")

    recs = generate_recommendations(d)
    n_critical = sum(1 for r in recs if r["severity"] == CRITICAL)
    n_warning = sum(1 for r in recs if r["severity"] == WARNING)
    n_watch = sum(1 for r in recs if r["severity"] == WATCH)

    section("Portfolio health")
    c = st.columns(4)
    kpi(c[0], "Critical", f"{n_critical}", "needs action now",
        BAD if n_critical else GOOD, top=BAD if n_critical else GOOD)
    kpi(c[1], "Warning", f"{n_warning}", "trending the wrong way",
        WARN if n_warning else MUTE, top=WARN if n_warning else PRIMARY)
    kpi(c[2], "Watch", f"{n_watch}", "keep an eye on it")
    kpi(c[3], "Total flagged", f"{len(recs)}", "actions across the portfolio")

    section("Recommended actions")
    if not recs:
        st.success("No thresholds breached — every tracked metric is inside its target range.")
    else:
        for r in recs:
            color, chip = _SEVERITY_STYLE[r["severity"]]
            action_card(color, chip, r["area"], r["title"], r["detail"])

    st.caption("Generated by a deterministic rule engine ([`insights.py`](insights.py)) using the "
              "same thresholds shown as color-coding on the other pages — not an AI-generated "
              "summary, so results are stable and fully explainable.")
